#!/usr/bin/env python3
"""Generate FIRMWARE/xrf_portable/include/metal_table.h from the engine.

The firmware's metal register is GENERATED from engine/metals.py — never
hand-copied — so the portable instrument can never drift from the desktop
certified one.  Regenerate after any registry change:

    python tools/gen_metal_table.py
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
XRF = os.path.abspath(os.path.join(HERE, os.pardir, os.pardir, os.pardir))
XRF = os.path.abspath(os.path.join(XRF))  # engine/ lives here
sys.path.insert(0, XRF)

from engine import metals as eng_metals                  # noqa: E402

OUT = os.path.join(XRF, "FIRMWARE", "xrf_portable", "include",
                   "metal_table.h")


def c_safe(s: str) -> str:
    return s.replace('"', '\\"')


def main() -> int:
    rows = []
    for m in eng_metals.registry():
        sig = m.conductivity_s_m if m.has_coil_signature else 0.0
        mu = m.rel_permeability or 1.0
        rows.append((m.z, m.symbol, m.category, sig, mu))
    dropped = eng_metals.dropped_from_registry()
    lines = [
        "// GENERATED by tools/gen_metal_table.py from engine/metals.py",
        f"// {len(rows)} XRF-readable metals + {len(dropped)} spoken drops."
        " DO NOT EDIT BY HAND.",
        "#pragma once",
        "#include <stddef.h>",
        "",
        "struct XrfMetal {",
        "  uint8_t z;",
        "  const char* sym;      // element symbol",
        "  const char* cat;      // registry category",
        "  float sigma;          // conductivity S/m (0 = XRF-only, spoken)",
        "  float mu_r;           // relative permeability",
        "};",
        "",
        f"#define XRF_N_METALS {len(rows)}",
        "static const XrfMetal XRF_METALS[XRF_N_METALS] = {",
    ]
    for z, sym, cat, sig, mu in rows:
        lines.append(f'  {{{z}, "{c_safe(sym)}", "{c_safe(cat)}", '
                     f"{sig!r}f, {mu!r}f}},")
    lines += [
        "};",
        "",
        f"#define XRF_N_DROPPED {len(dropped)}"
        "  // below-window metals, SPOKEN (Law 171)",
        "static const char* const XRF_DROPPED[XRF_N_DROPPED] = {",
    ]
    for sym, _cat, _ev in dropped:
        lines.append(f'  "{c_safe(sym)}",')
    lines += ["};", "static const float XRF_DROPPED_BEST_EV[XRF_N_DROPPED] = {"]
    for _sym, _cat, ev in dropped:
        lines.append(f"  {ev!r}f,")
    lines += [
        "};",
        "",
        "#define XRF_KA1_OFFSET_MICRON 0  // the register's primary line is",
        "                            // emitted by the desktop chain; the",
        "                            // firmware reads the FEED path",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(rows)} metals, {len(dropped)} dropped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
